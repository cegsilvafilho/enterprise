## Métricas de sucesso

### Produto

- usuários ativos;
- check-ins por semana;
- mensagens respondidas;
- planos de crise completos;
- alertas resolvidos.

### Assistencial

- tempo de primeira resposta;
- controle de sintomas;
- crises acompanhadas;
- cuidadores apoiados;
- reuniões familiares registradas.

### Operação

- SLA cumprido;
- fila em atraso;
- produtividade da equipe;
- pacientes por profissional;
- unidades ativas.

### Negócio

- instituições interessadas;
- pilotos ativos;
- conversão para contrato;
- custo por paciente acompanhado;
- valor percebido pelo gestor.

