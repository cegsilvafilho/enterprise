# Roadmap e backlog

## Fase 0: protótipo e validação

Objetivo:

- validar proposta;
- testar fluxos com dados fictícios;
- apresentar a instituições;
- entender prioridades.

Entregáveis:

- protótipo navegável;
- pitch;
- documentação;
- base no-code;
- feedback de usuários.

## Fase 1: MVP operacional

Objetivo:

Ter uma versão usável em piloto controlado.

Épicos:

- login por perfil;
- cadastro de paciente;
- cuidador autorizado;
- check-in;
- prioridade;
- alertas;
- fila profissional;
- plano de crise;
- plano de cuidado;
- condutas;
- dashboard gestor básico;
- auditoria mínima.

Critérios de aceite:

- paciente só vê próprios dados;
- cuidador só vê autorizado;
- profissional vê fila;
- alerta tem status e responsável;
- gestor vê indicadores agregados;
- ações sensíveis são auditadas.

## Fase 2: cuidado paliativo completo

Épicos:

- funcionalidade;
- escalas;
- sobrecarga do cuidador;
- reuniões familiares;
- planejamento antecipado;
- preferências;
- suporte social;
- espiritualidade;
- luto.

## Fase 3: operação institucional

Épicos:

- unidades;
- equipes;
- linhas de cuidado;
- protocolos;
- SLA avançado;
- relatórios;
- implantação guiada;
- painel de qualidade.

## Fase 4: integrações

Épicos:

- prontuário;
- agenda;
- exames;
- teleatendimento;
- notificações;
- operadora;
- BI externo.

## Fase 5: inteligência

Épicos:

- previsão de crise;
- sugestões de próxima ação;
- segmentação;
- benchmark;
- dados de mundo real;
- análise de desfechos.

